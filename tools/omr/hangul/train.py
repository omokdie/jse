#!/usr/bin/env python3
"""Train the JSE Hangul lyric recogniser (numpy only) and export it to JS.

  python3 tools/omr/hangul/train.py                      # data + training + export (~15 min on 2 CPUs)
  python3 tools/omr/hangul/train.py --epochs 3 --train-count 100000 --no-export   # quick experiment
  python3 tools/omr/hangul/train.py --resume             # continue from the last checkpoint
  python3 tools/omr/hangul/train.py --eval-only          # re-evaluate the saved model
  python3 tools/omr/hangul/train.py --fixtures           # (re)write the JS parity fixtures only

Model: gradient-direction features (8 directions x 8x8 grid, sqrt) + 16x16 ink
(core.features, 768-d) -> MLP (ReLU) -> four softmax heads: type (HANGUL /
symbols / NOISE), initial (19), medial (21), final (28). Hangul samples train
all heads, other samples only the type head.

Data is generated by gen_data.py into --data (default /tmp/jse-hangul) and
reused when present (delete the directory or pass --regen to rebuild it).
Outputs: <data>/model.npz (float weights, checkpoint), the JS module
app/js/omr/hangul-weights.js (int8 weights, base64) and
tools/tests/fixtures/hangul-fixtures.json (parity test for the JS port).
"""
import argparse, base64, json, math, os, sys, time
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from charset import (TYPE_CLASSES, HANGUL_T, NOISE_T, N_INI, N_MED, N_FIN, SYMBOLS,  # noqa: E402
                     ks_x_1001_syllables, decompose, compose)
from core import features, FEAT_DIM, EM_BOX, PAPER_PCT, INK_PCT, MIN_CONTRAST, CROP  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
JS_OUT = os.path.join(ROOT, 'app', 'js', 'omr', 'hangul-weights.js')
FIXTURES = os.path.join(ROOT, 'tools', 'tests', 'fixtures', 'hangul-fixtures.json')
NT = len(TYPE_CLASSES)
HEADS = [('type', NT), ('ini', N_INI), ('med', N_MED), ('fin', N_FIN)]
NOUT = sum(n for _, n in HEADS)
OFFS = np.cumsum([0] + [n for _, n in HEADS])
KS = ks_x_1001_syllables()
KS_IDX = np.array([decompose(c) for c in KS])          # (2350, 3)


# ---------------------------------------------------------------------------
# data
# ---------------------------------------------------------------------------
def dataset(path, mode, count, seed, regen, procs):
    if os.path.exists(path) and not regen:
        d = np.load(path)
        if len(d['X']) >= count:
            return d['X'][:count], d['L'][:count], d['F'][:count], d['C'][:count]
    import gen_data
    t0 = time.time()
    X, L, F, C = gen_data.generate_parallel(mode, count, seed, procs)
    np.savez(path, X=X, L=L, F=F, C=C)
    print(f'generated {mode}: {count} samples in {time.time() - t0:.0f}s', flush=True)
    return X, L, F, C


def feats_of(X, bs=2048):
    out = np.empty((len(X), FEAT_DIM), np.float32)
    for i in range(0, len(X), bs):
        out[i:i + bs] = features(X[i:i + bs].astype(np.float64) / 255.0)
    return out


# ---------------------------------------------------------------------------
# model
# ---------------------------------------------------------------------------
def init_model(hidden, rng):
    dims = [FEAT_DIM] + hidden + [NOUT]
    Ws, bs = [], []
    for a, b in zip(dims[:-1], dims[1:]):
        Ws.append((rng.standard_normal((a, b)) * math.sqrt(2.0 / a)).astype(np.float32))
        bs.append(np.zeros(b, np.float32))
    return {'W': Ws, 'b': bs}


def forward(model, x, train=False, drop=0.0, rng=None):
    acts = [x]
    h = x
    n = len(model['W'])
    masks = []
    for li in range(n):
        z = h @ model['W'][li] + model['b'][li]
        if li < n - 1:
            h = np.maximum(z, 0)
            if train and drop > 0:
                m = (rng.random(h.shape) >= drop).astype(np.float32) / (1 - drop)
                h = h * m
                masks.append(m)
            else:
                masks.append(None)
            acts.append(h)
        else:
            h = z
    return h, acts, masks


def head_softmax(logits):
    out = []
    for k in range(len(HEADS)):
        z = logits[:, OFFS[k]:OFFS[k + 1]]
        z = z - z.max(axis=1, keepdims=True)
        e = np.exp(z)
        out.append(e / e.sum(axis=1, keepdims=True))
    return out


def loss_grad(logits, L):
    """Cross entropy over the heads; jamo heads only for Hangul samples."""
    probs = head_softmax(logits)
    N = len(L)
    g = np.zeros_like(logits)
    loss = 0.0
    hang = L[:, 0] == HANGUL_T
    for k in range(len(HEADS)):
        p = probs[k]
        y = L[:, k]
        valid = np.ones(N, bool) if k == 0 else hang
        idx = np.nonzero(valid)[0]
        if not len(idx):
            continue
        loss += -np.log(p[idx, y[idx]] + 1e-9).sum() / N
        gk = p.copy()
        gk[idx, y[idx]] -= 1
        gk[~valid] = 0
        g[:, OFFS[k]:OFFS[k + 1]] = gk / N
    return loss, g


def backward(model, acts, masks, g, wd):
    n = len(model['W'])
    gW, gb = [None] * n, [None] * n
    for li in range(n - 1, -1, -1):
        gW[li] = acts[li].T @ g + wd * model['W'][li]
        gb[li] = g.sum(axis=0)
        if li > 0:
            g = g @ model['W'][li].T
            g = g * (acts[li] > 0)
            if masks[li - 1] is not None:
                g = g * masks[li - 1]
    return gW, gb


class Adam:
    def __init__(self, model, lr):
        self.lr = lr
        self.t = 0
        self.m = [np.zeros_like(w) for w in model['W'] + model['b']]
        self.v = [np.zeros_like(w) for w in model['W'] + model['b']]

    def step(self, model, grads, lr):
        self.t += 1
        params = model['W'] + model['b']
        b1, b2, eps = 0.9, 0.999, 1e-8
        c1, c2 = 1 - b1 ** self.t, 1 - b2 ** self.t
        for i, (p, g) in enumerate(zip(params, grads)):
            self.m[i] = b1 * self.m[i] + (1 - b1) * g
            self.v[i] = b2 * self.v[i] + (1 - b2) * (g * g)
            p -= lr * (self.m[i] / c1) / (np.sqrt(self.v[i] / c2) + eps)


