# decoding / evaluation
# ---------------------------------------------------------------------------
PRIOR_JSON = os.path.join(HERE, 'syllable_prior.json')
PRIOR_STEP = 0.05


def load_prior(alpha=3.0):
    """Quantised log unigram prior over the KS syllables (uint8: -log p/step,
    relative to the most frequent syllable), or None."""
    if not os.path.exists(PRIOR_JSON):
        return None
    doc = json.load(open(PRIOR_JSON, encoding='utf-8'))
    c = np.array([doc['counts'].get(ch, 0) for ch in KS], np.float64) + alpha
    lp = np.log(c / c.sum())
    q = np.clip(np.round((lp.max() - lp) / PRIOR_STEP), 0, 254).astype(np.uint8)
    return q


def decode(probs, ks_only=True, prior_q=None, weight=0.0):
    """Returns (type idx, syllable char or None, confidence) per sample."""
    pt, pi, pm, pf = probs
    out = []
    li, lm, lf = np.log(pi + 1e-9), np.log(pm + 1e-9), np.log(pf + 1e-9)
    pr = -prior_q.astype(np.float64) * PRIOR_STEP * weight if prior_q is not None and weight else 0.0
    for n in range(len(pt)):
        t = int(np.argmax(pt[n]))
        if t != HANGUL_T:
            out.append((t, None, float(pt[n, t])))
            continue
        if ks_only:
            s = li[n, KS_IDX[:, 0]] + lm[n, KS_IDX[:, 1]] + lf[n, KS_IDX[:, 2]]
            j = int(np.argmax(s + pr))
            ch = KS[j]
            conf = float(pt[n, t] * math.exp(s[j]))
        else:
            i, m, f = int(np.argmax(pi[n])), int(np.argmax(pm[n])), int(np.argmax(pf[n]))
            ch = compose(i, m, f)
            conf = float(pt[n, t] * pi[n, i] * pm[n, m] * pf[n, f])
        out.append((t, ch, conf))
    return out


def predict(model, mu, sd, F, bs=4096):
    outs = []
    for i in range(0, len(F), bs):
        x = (F[i:i + bs] - mu) / sd
        lg, _, _ = forward(model, x)
        outs.append(lg)
    return head_softmax(np.concatenate(outs))


def evaluate(model, mu, sd, F, L, C, Fo=None, label=''):
    probs = predict(model, mu, sd, F)
    dec = decode(probs, ks_only=True)
    dec_free = decode(probs, ks_only=False)
    hang = L[:, 0] == HANGUL_T
    sym = (L[:, 0] != HANGUL_T) & (L[:, 0] != NOISE_T)
    ok_ks = np.array([d[1] is not None and ord(d[1]) == c for d, c in zip(dec, C)])
    ok_free = np.array([d[1] is not None and ord(d[1]) == c for d, c in zip(dec_free, C)])
    ok_sym = np.array([d[0] == t for d, t in zip(dec, L[:, 0])])
    jam = [np.mean(np.argmax(probs[k + 1][hang], axis=1) == L[hang, k + 1]) for k in range(3)]
    res = {'hangul_n': int(hang.sum()), 'syllable_acc': float(ok_ks[hang].mean()), 'syllable_acc_free': float(ok_free[hang].mean()),
           'symbol_n': int(sym.sum()), 'symbol_acc': float(ok_sym[sym].mean()) if sym.any() else None,
           'type_hangul_recall': float((np.argmax(probs[0][hang], axis=1) == HANGUL_T).mean()),
           'jamo_acc': [float(j) for j in jam]}
    if Fo is not None:
        import gen_data
        res['per_font'] = {gen_data.FONTS[fi][0]: round(float(ok_ks[hang & (Fo == fi)].mean()), 4) for fi in sorted(set(Fo[hang].tolist()))}
    print(f'[{label}] syllables {res["syllable_acc"] * 100:.2f}% (KS-constrained; free {res["syllable_acc_free"] * 100:.2f}%) n={res["hangul_n"]}'
          f' | symbols {res["symbol_acc"] * 100 if res["symbol_acc"] is not None else 0:.2f}% n={res["symbol_n"]}'
          f' | jamo {" ".join(f"{j * 100:.1f}" for j in jam)}', flush=True)
    return res


