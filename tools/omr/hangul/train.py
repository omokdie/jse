# export
# ---------------------------------------------------------------------------
def b64(a):
    return base64.b64encode(np.ascontiguousarray(a).tobytes()).decode('ascii')


def quantize_layers(model, mu, sd):
    """Folds the feature standardisation into layer 1 and quantises every
    weight matrix to int8 with one fp32 scale per output unit."""
    Ws = [w.astype(np.float64) for w in model['W']]
    bs = [b.astype(np.float64) for b in model['b']]
    W0 = Ws[0] / sd[:, None]
    b0 = bs[0] - (mu / sd) @ Ws[0]
    Ws[0], bs[0] = W0, b0
    layers = []
    for W, b in zip(Ws, bs):
        scale = np.abs(W).max(axis=0) / 127.0
        scale[scale == 0] = 1e-12
        q = np.clip(np.round(W / scale[None, :]), -127, 127).astype(np.int8)
        layers.append({'in': W.shape[0], 'out': W.shape[1], 'q': q.T.copy(), 'scale': scale.astype(np.float32), 'bias': b.astype(np.float32)})
    return layers


def dequantized_model(layers):
    return {'W': [(L['q'].T.astype(np.float32) * L['scale'][None, :]) for L in layers], 'b': [L['bias'] for L in layers]}


def ks_bitmap():
    bits = np.zeros((11172 + 7) // 8, np.uint8)
    for c in KS:
        k = ord(c) - 0xAC00
        bits[k >> 3] |= 1 << (k & 7)
    return bits


def export_js(layers, meta, prior_weight=0.6):
    parts = []
    for L in layers:
        parts.append({'in': L['in'], 'out': L['out'], 'w': b64(L['q']), 'scale': b64(L['scale']), 'bias': b64(L['bias'])})
    doc = {
        'version': meta['version'], 'crop': CROP, 'emBox': EM_BOX, 'paperPct': PAPER_PCT, 'inkPct': INK_PCT, 'minContrast': MIN_CONTRAST,
        'featDim': FEAT_DIM, 'types': TYPE_CLASSES, 'heads': [[n, k] for n, k in HEADS], 'ks': b64(ks_bitmap()), 'layers': parts,
        'accuracy': meta.get('accuracy', {}),
    }
    q = load_prior()
    if q is not None and prior_weight > 0:
        doc['prior'] = {'q': b64(q), 'step': PRIOR_STEP, 'weight': prior_weight,
                        'source': 'Tesseract kor word list syllable counts (tools/omr/hangul/syllable_prior.json)'}
    body = json.dumps(doc, ensure_ascii=False, separators=(',', ':'))
    js = ('// Generated by tools/omr/hangul/train.py — do not edit by hand.\n'
          '// Hangul lyric recogniser weights: int8 matrices (one fp32 scale per output unit) and\n'
          '// fp32 biases, base64 little-endian; `ks` = bitmap of the 2,350 KS X 1001 syllables.\n'
          f'export const HANGUL_MODEL = {body};\n')
    with open(JS_OUT, 'w') as f:
        f.write(js)
    print(f'wrote {os.path.relpath(JS_OUT, ROOT)} ({len(js) / 1024:.0f} KB)')


def write_fixtures(layers, X, L, C, rng, n=24, prior_weight=0.6):
    """Inputs + expected outputs for tools/tests/hangul.test.js: a few raw
    grey crops (to test em-box sampling + normalisation + features) and ink
    maps with the expected logits of the quantised model."""
    from core import sample_embox, normalize_ink
    os.makedirs(os.path.dirname(FIXTURES), exist_ok=True)
    model = dequantized_model(layers)
    idx = rng.choice(len(X), n, replace=False)
    ink = X[idx].astype(np.float64) / 255.0
    F = features(ink)
    lg, _, _ = forward(model, F.astype(np.float32))
    probs = head_softmax(lg)
    dec = decode(probs, prior_q=load_prior(), weight=prior_weight)
    samples = []
    for k, i in enumerate(idx):
        samples.append({'ink': b64(X[i]), 'label': int(L[i, 0]), 'char': chr(int(C[i])) if C[i] else None,
                        'feat': [round(float(v), 6) for v in F[k][::37]], 'featStride': 37,
                        'logits': [round(float(v), 4) for v in lg[k]], 'decoded': dec[k][1] or TYPE_CLASSES[dec[k][0]]})
    # em-box sampling fixture: a synthetic grey image and a few crops
    g = np.full((40, 60), 230.0)
    yy, xx = np.mgrid[0:40, 0:60]
    g -= 180.0 * (((xx - 30.3) ** 2 / 64 + (yy - 19.6) ** 2 / 36) < 1)
    g -= 150.0 * ((np.abs(xx - 12) < 2) & (yy > 8) & (yy < 30))
    g = np.round(g)
    crops = []
    for (cx, cy, S, A) in [(30.0, 20.0, 24.0, None), (29.5, 19.2, 70.0, None), (14.2, 18.7, 20.5, [[0.9, -0.1, 3.0], [0.12, 1.05, -2.0]])]:
        crop = sample_embox(g, cx, cy, S, affine=None if A is None else np.array(A))
        inkm = normalize_ink(crop)
        crops.append({'cx': cx, 'cy': cy, 'S': S, 'affine': A, 'sum': round(float(crop.sum()), 4), 'ink': b64(np.round(inkm * 255).astype(np.uint8))})
    doc = {'samples': samples, 'image': {'w': 60, 'h': 40, 'data': b64(g.astype(np.uint8))}, 'crops': crops}
    with open(FIXTURES, 'w') as f:
        json.dump(doc, f)
    print(f'wrote {os.path.relpath(FIXTURES, ROOT)}')


# ---------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--data', default='/tmp/jse-hangul')
    ap.add_argument('--train-count', type=int, default=600000)
    ap.add_argument('--eval-count', type=int, default=20000)
    ap.add_argument('--hidden', default='512,384')
    ap.add_argument('--epochs', type=int, default=12)
    ap.add_argument('--batch', type=int, default=512)
    ap.add_argument('--lr', type=float, default=2e-3)
    ap.add_argument('--wd', type=float, default=1e-5)
    ap.add_argument('--drop', type=float, default=0.0)
    ap.add_argument('--seed', type=int, default=1)
    ap.add_argument('--procs', type=int, default=2)
    ap.add_argument('--regen', action='store_true')
    ap.add_argument('--resume', action='store_true')
    ap.add_argument('--eval-only', action='store_true')
    ap.add_argument('--fixtures', action='store_true')
    ap.add_argument('--no-export', action='store_true')
    ap.add_argument('--time-budget', type=float, default=560, help='stop training after this many seconds (checkpoint is saved)')
    ap.add_argument('--tag', default='model')
    ap.add_argument('--prior-weight', type=float, default=0.6, help='weight of the syllable prior in the JS decoder (0 = off; 0.6 tuned on a dev corpus)')
    ap.add_argument('--export-only', action='store_true', help='export the saved model to JS (+ fixtures) without training')
    args = ap.parse_args()
    os.makedirs(args.data, exist_ok=True)
    rng = np.random.default_rng(args.seed)
    ckpt = os.path.join(args.data, args.tag + '.npz')

    Xc, Lc, Fc, Cc = dataset(os.path.join(args.data, 'clean.npz'), 'clean', args.eval_count, 9001, args.regen, args.procs)
    Xd, Ld, Fd, Cd = dataset(os.path.join(args.data, 'degraded.npz'), 'degraded', args.eval_count, 9002, args.regen, args.procs)
    Fcl, Fdg = feats_of(Xc), feats_of(Xd)

    if args.eval_only or args.fixtures or args.export_only:
        d = np.load(ckpt, allow_pickle=True)
        model = {'W': list(d['W']), 'b': list(d['b'])}
        mu, sd = d['mu'], d['sd']
        layers = quantize_layers(model, mu, sd)
        if args.fixtures or args.export_only:
            if args.export_only:
                rep = json.load(open(os.path.join(args.data, args.tag + '_report.json'))) if os.path.exists(os.path.join(args.data, args.tag + '_report.json')) else {}
                acc = {k: round(rep[k + '_int8']['syllable_acc'], 4) for k in ('clean', 'degraded') if k + '_int8' in rep}
                export_js(layers, {'version': time.strftime('%Y%m%d'), 'accuracy': acc}, args.prior_weight)
            write_fixtures(layers, Xd, Ld, Cd, rng, prior_weight=args.prior_weight)
            return
        qm = dequantized_model(layers)
        one = np.zeros(FEAT_DIM, np.float32)
        r1 = evaluate(model, mu, sd, Fcl, Lc, Cc, Fc, 'clean float')
        r2 = evaluate(model, mu, sd, Fdg, Ld, Cd, Fd, 'degraded float')
        evaluate(qm, one, one + 1, Fcl, Lc, Cc, None, 'clean int8')
        evaluate(qm, one, one + 1, Fdg, Ld, Cd, None, 'degraded int8')
        print(json.dumps({'clean': r1, 'degraded': r2}, ensure_ascii=False, indent=1))
        return

    X, L, Fo, C = dataset(os.path.join(args.data, 'train.npz'), 'train', args.train_count, args.seed, args.regen, args.procs)
    t0 = time.time()
    feat_path = os.path.join(args.data, f'train_feat_{len(X)}.npy')
    if os.path.exists(feat_path) and not args.regen:
        Ftr = np.load(feat_path, mmap_mode=None)
    else:
        Ftr = feats_of(X).astype(np.float16)
        np.save(feat_path, Ftr)
    print(f'features: {Ftr.shape} in {time.time() - t0:.0f}s', flush=True)
    hidden = [int(h) for h in args.hidden.split(',') if h]
    start_epoch = 0
    if args.resume and os.path.exists(ckpt):
        d = np.load(ckpt, allow_pickle=True)
        model = {'W': list(d['W']), 'b': list(d['b'])}
        mu, sd = d['mu'], d['sd']
        start_epoch = int(d['epoch'])
        opt = Adam(model, args.lr)
        if 'adam_m' in d.files:
            opt.m, opt.v, opt.t = list(d['adam_m']), list(d['adam_v']), int(d['adam_t'])
        print(f'resumed {ckpt} at epoch {start_epoch}')
    else:
        sub = Ftr[rng.choice(len(Ftr), min(100000, len(Ftr)), replace=False)].astype(np.float32)
        mu = sub.mean(axis=0)
        sd = sub.std(axis=0) + 1e-3
        model = init_model(hidden, rng)
        opt = Adam(model, args.lr)
    N = len(Ftr)
    steps_per_epoch = N // args.batch
    total = steps_per_epoch * args.epochs
    t_start = time.time()
    for ep in range(start_epoch, args.epochs):
        perm = rng.permutation(N)
        tl, tn = 0.0, 0
        for s in range(steps_per_epoch):
            step = ep * steps_per_epoch + s
            lr = args.lr * (0.5 * (1 + math.cos(math.pi * step / total))) if step > 300 else args.lr * (step + 1) / 300
            idx = perm[s * args.batch:(s + 1) * args.batch]
            x = (Ftr[idx].astype(np.float32) - mu) / sd
            logits, acts, masks = forward(model, x, train=True, drop=args.drop, rng=rng)
            loss, g = loss_grad(logits, L[idx])
            gW, gb = backward(model, acts, masks, g.astype(np.float32), args.wd)
            opt.step(model, gW + gb, lr)
            tl += loss
            tn += 1
        el = time.time() - t_start
        print(f'epoch {ep + 1}/{args.epochs} loss {tl / tn:.4f} lr {lr:.2e} ({el:.0f}s)', flush=True)
        evaluate(model, mu, sd, Fcl[:5000], Lc[:5000], Cc[:5000], None, 'clean')
        evaluate(model, mu, sd, Fdg[:5000], Ld[:5000], Cd[:5000], None, 'degraded')
        np.savez(ckpt, W=np.array(model['W'], dtype=object), b=np.array(model['b'], dtype=object), mu=mu, sd=sd, epoch=ep + 1,
                 hidden=np.array(hidden), adam_m=np.array(opt.m, dtype=object), adam_v=np.array(opt.v, dtype=object), adam_t=opt.t)
        if time.time() - t_start > args.time_budget and ep + 1 < args.epochs:
            print(f'time budget reached after epoch {ep + 1}; continue with --resume')
            return
    r1 = evaluate(model, mu, sd, Fcl, Lc, Cc, Fc, 'clean (final)')
    r2 = evaluate(model, mu, sd, Fdg, Ld, Cd, Fd, 'degraded (final)')
    layers = quantize_layers(model, mu, sd)
    qm = dequantized_model(layers)
    one = np.zeros(FEAT_DIM, np.float32)
    q1 = evaluate(qm, one, one + 1, Fcl, Lc, Cc, None, 'clean int8')
    q2 = evaluate(qm, one, one + 1, Fdg, Ld, Cd, None, 'degraded int8')
    with open(os.path.join(args.data, args.tag + '_report.json'), 'w') as f:
        json.dump({'clean': r1, 'degraded': r2, 'clean_int8': q1, 'degraded_int8': q2, 'hidden': hidden, 'train': N, 'epochs': args.epochs}, f, ensure_ascii=False, indent=1)
