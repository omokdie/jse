#!/usr/bin/env python3
"""Export tiny binary glyph templates (FreeSerif) for the OMR classifier
to app/js/omr/templates.js.  Each template is a bbox-cropped 1-bit mask
packed row-major (MSB first) and base64 encoded; `hsp`/`wsp` give the glyph
size in staff spaces so the matcher can apply a size prior.  ~3 KB total.
"""
import base64, json, os, sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from music_glyphs import GlyphRaster  # noqa: E402

SP = 20.0   # render size; templates are rescaled at run time
NAMES = {
    'd0': 'digit0', 'd1': 'digit1', 'd2': 'digit2', 'd3': 'digit3', 'd4': 'digit4',
    'd5': 'digit5', 'd6': 'digit6', 'd7': 'digit7', 'd8': 'digit8', 'd9': 'digit9',
    'common': 'common', 'cut': 'cut',
    'restQuarter': 'restQuarter', 'rest8th': 'rest8th', 'rest16th': 'rest16th', 'rest32nd': 'rest32nd',
    'sharp': 'sharp', 'flat': 'flat', 'natural': 'natural',
    'gClef': 'gClef', 'fClef': 'fClef', 'cClef': 'cClef',
}


def main():
    gr = GlyphRaster()
    out = {}
    for key, name in NAMES.items():
        alpha, ox, oy = gr.render(name, SP)
        mask = alpha > 0.5
        ys, xs = np.where(mask)
        y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
        mask = mask[y0:y1, x0:x1]
        h, w = mask.shape
        # the bass clef's two dots are separate components in a real image;
        # keep only the main curl so the template matches what segmentation yields
        if key == 'fClef':
            col_ink = mask.sum(axis=0)
            cut = int(w * 0.72)
            while cut < w and col_ink[cut] > 0:
                cut += 1
            mask = mask[:, :cut]; h, w = mask.shape
        bits = np.packbits(mask.astype(np.uint8), axis=1)
        out[key] = {'w': int(w), 'h': int(h), 'wsp': round(w / SP, 3), 'hsp': round(h / SP, 3),
                    'bits': base64.b64encode(bits.tobytes()).decode('ascii')}
    js = ('// Auto-generated by tools/omr/gen_templates.py from GNU FreeSerif (GPLv3+FE).\n'
          '// 1-bit glyph masks, rows packed MSB-first, base64. Sizes in staff spaces.\n'
          'export const TEMPLATES = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'app', 'js', 'omr', 'templates.js')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(js)
    print('wrote', os.path.normpath(path), len(js), 'bytes')
    for k, v in out.items():
        print(f"{k:12s} {v['w']:3d}x{v['h']:3d}  {v['wsp']:.2f}x{v['hsp']:.2f} sp")


if __name__ == '__main__':
    main()
