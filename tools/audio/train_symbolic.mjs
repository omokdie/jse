#!/usr/bin/env node
// Symbolic "training" from the Finale corpus (no audio needed) for two decisions of the audio → score pipeline:
//   1. key signature: a naive-Bayes model — pitch-class profile relative to the signature's major tonic, plus a
//      prior over signatures — learned from the concert-pitch notes and key of every non-holdout piece;
//   2. examples for the tempo-octave chooser (written onsets of excerpts) → /tmp/jse-symbolic.json.
//   nice -n 10 node tools/audio/train_symbolic.mjs [--cache /home/claude/enigma-cache] [--out app/js/audio/keymodel.js]
// Pieces whose hash split (same rule as gen_corpus.mjs) is "holdout" are never read.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { enigmaToScore } from '../../app/js/io/musx.js';
import { durTicks, midiOf, measureCapacity, effectiveTimeSig, effectiveKeySig, staffList } from '../../app/js/model/score.js';

const argv = process.argv.slice(2), arg = (k, d) => { const i = argv.indexOf('--' + k); return i < 0 ? d : argv[i + 1]; };
const CACHE = arg('cache', '/home/claude/enigma-cache');
const OUT = arg('out', path.join(path.dirname(new URL(import.meta.url).pathname), '../../app/js/audio/keymodel.js'));
function hash(s) { let h = 2166136261 >>> 0; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619) >>> 0; } return h >>> 0; }
const splitOf = name => { const h = hash(name) % 100; return h < 60 ? 'train' : h < 80 ? 'dev' : 'holdout'; };

const files = fs.readdirSync(CACHE).filter(f => f.endsWith('.xml.gz') && splitOf(f) !== 'holdout').sort();
const prof = new Float64Array(12), prior = new Float64Array(13);
const examples = [];
let used = 0;
for (const f of files) {
  let score; try { score = enigmaToScore(zlib.gunzipSync(fs.readFileSync(path.join(CACHE, f))).toString('utf8'), { meta: null }); } catch { continue; }
  const st = staffList(score);
  // excerpt windows of 16 measures with a single key/meter (the audio corpus uses excerpts too)
  for (let start = 0; start < score.measures.length; start += 16) {
    const end = Math.min(score.measures.length, start + 16);
    if (score.measures.slice(start + 1, end).some(m => m.keySig || m.timeSig)) continue;
    const ks = effectiveKeySig(score, start), ts = effectiveTimeSig(score, start);
    const h = new Float64Array(12); const ons = [];
    let q0 = 0;
    for (let mi = start; mi < end; mi++) {
      const m = score.measures[mi];
      m.staves.forEach((sm, si) => {
        const s = st[si]; if (!s || s.staff.type !== 'standard') return;
        const tr = s.part.transposeChromatic || 0;
        sm.voices.forEach(v => { let t = 0; for (const ev of v) { const d = durTicks(ev); if (ev.kind === 'note' && !ev.grace && d > 0) for (const n of ev.notes) { const p = midiOf(n) + tr; h[((p % 12) + 12) % 12] += Math.min(2, d / 960); if (!n.tieEnd) ons.push([+(q0 + t / 960).toFixed(4), +(d / 960).toFixed(4), p, si]); } t += d; } });
      });
      q0 += measureCapacity(effectiveTimeSig(score, mi)) / 960;
    }
    const tot = h.reduce((a, b) => a + b, 0); if (tot < 4) continue;
    if (ks.fifths < -6 || ks.fifths > 6) continue;
    const tonic = ((ks.fifths * 7) % 12 + 12) % 12;
    for (let c = 0; c < 12; c++) prof[c] += h[(c + tonic) % 12] / tot;
    prior[ks.fifths + 6]++;
    used++;
    if (examples.length < 4000 && ons.length >= 8) examples.push({ f, start, ts: [ts.num, ts.den], fifths: ks.fifths, ons });
  }
}
const ps = prof.reduce((a, b) => a + b, 0), pr = prior.reduce((a, b) => a + b, 0);
const logProf = Array.from(prof, v => +Math.log(v / ps + 1e-4).toFixed(4));
const logPrior = Array.from(prior, v => +Math.log((v + 1) / (pr + 13)).toFixed(4));
fs.writeFileSync(OUT, `// Generated by tools/audio/train_symbolic.mjs from ${used} 16-bar excerpts of the non-holdout Finale corpus — do not edit.
// logProfile[c]: log share of pitch class c semitones above the key signature's major tonic; logPrior[f + 6]: signature prior.
export const KEY_MODEL = { excerpts: ${used}, logProfile: ${JSON.stringify(logProf)}, logPrior: ${JSON.stringify(logPrior)} };
`);
fs.writeFileSync('/tmp/jse-symbolic.json', JSON.stringify(examples));
console.log('excerpts', used, 'files', files.length, 'examples', examples.length);
console.log('profile', Array.from(prof, v => (v / ps).toFixed(3)).join(' '));
console.log('prior', Array.from(prior).join(' '));
